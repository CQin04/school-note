# 题目要求： 兔子出生两个月后可繁殖，每对兔子每月繁殖一对，假定不死亡。编写递归函数，根据月份计算兔子总对数，并考虑一年后的数量。第 1、2 个月各为 1 对；此后每月数量等于前两个月数量之和。按此规则，第 12 个月为 144 对。

def f(n):
    if n == 1 or n == 2:
        return 1
    else:
        return f(n-1) + f(n-2)
for i in range(1, 13):
    print(f'经过第{i}个月后的兔子对数是:{f(i)}')
