# 题目要求： 接收商品价格并打印购物小票，包含商品名称、数量、单价及金额。示例商品包括金士顿 U 盘、胜创 TF 卡、读卡器和网线；使用 input() 接收价格，使用 print() 输出小票，并显示总数、总额、折后总额、实收、找零和收银员。PDF 示例输入 40、50、8、5，显示 4 件、总额 103 元。课程作业页面另要求购物数量和价格均由键盘输入、打 8.8 折，收银员为自己的名字。

U盘单价 = float(input('扫描U盘的价格: '))
U盘数量 = int(input('扫描U盘的数量: '))

TF卡单价 = float(input('扫描TF卡的价格: '))
TF卡数量 = int(input('扫描TF卡的数量: '))

读卡器单价 = float(input('扫描读卡器的价格: '))
读卡器数量 = int(input('扫描读卡器的数量: '))

网线单价 = float(input('扫描网线的价格: '))
网线数量 = int(input('扫描网线的数量: '))

单号 = input('请输入单号: ')

print('..................................')
print('单号: DH', 单号,sep='')
print('时间: 2026-10-13 01:54:00')
print('..................................')

print('名称         数量       单价           金额')
print('金士顿U盘     ', U盘数量, '      ', U盘单价, '   ', U盘数量 * U盘单价)
print('胜创16G TF卡  ', TF卡数量, '      ', TF卡单价, '    ', TF卡数量 * TF卡单价)
print('读卡器        ', 读卡器数量, '      ', 读卡器单价, '    ', 读卡器数量 * 读卡器单价)
print('网线2米       ', 网线数量, '      ', 网线单价, '   ', 网线数量 * 网线单价)
print('..................................')

总数 = U盘数量 + TF卡数量 + 读卡器数量 + 网线数量
总额 = U盘数量 * U盘单价 + TF卡数量 * TF卡单价 + 读卡器数量 * 读卡器单价 + 网线数量 * 网线单价
折后总额 = (U盘数量 * U盘单价 + TF卡数量 * TF卡单价 + 读卡器数量 * 读卡器单价 + 网线数量 * 网线单价) * 0.88

print('总数: ', 总数,'      总额: ', 总额)
print('折扣: 8.8折')
print('折后总额: ', 折后总额)

支付价格 = float(input('请输入支付价格: '))
找零 = 支付价格 - 折后总额
print('实收: ', f'{支付价格:.2f}', '      找零: ', f'{找零:.2f}')
