# 实现账号密码检测功能，账号:名字首字母缩写，密码:学号后两位
print("示例账号: name  密码: 123456")
# 登陆失败的次数
count = 0 

while count < 3:
    username = input("请输入您的账号：")
    pwd = input("请输入您的密码：")

    if username == 'name' and pwd == '123456':
        print('登录成功')
        break
    else:
        count += 1
        print(f'账号或密码错误，您还有{3 - count}次机会')
    if count == 3:
        print('账号或密码错误次数过多，请稍后再试')
        break