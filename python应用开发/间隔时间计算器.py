# 题目要求： 输入起始时间和结束时间各自的小时、分钟，计算并输出相差的小时数和分钟数。例如 17:10 至 18:15 的间隔为 1 小时 5 分钟。

# 1. 输入起始时间的小时数和分钟数。
# 2. 输入结束时间的小时数和分钟数。
# 3. 计算两个时间点的时间间隔。这里可以首先将起始时间的小时数与分钟数都换算成
#    分钟数，得到起始时间的总分钟数，其次将结束时间的小时数与分钟数都换算成分
#    钟数，得到结束时间的总分钟数，然后计算起始时间和结束时间相差的分钟数，最
#    后将分钟数转换为小时数和分钟数。
# 4. 输出时间间隔

print("请输入起始时间：")
start_hour = int(input("小时数: "))
start_minute = int(input("分钟数: "))

print("请输入结束时间：")
end_hour = int(input("小时数: "))
end_minute = int(input("分钟数: "))

# 将起始时间和结束时间转换为总分钟数
start_time = start_hour * 60 + start_minute
end_time = end_hour * 60 + end_minute

# 计算时间间隔
时间间隔 = end_time - start_time

# 将分钟数转换为小时数和分钟数
小时数 = 时间间隔 // 60
分钟数 = 时间间隔 % 60

print(f"时间间隔: {小时数}小时{分钟数}分钟")
